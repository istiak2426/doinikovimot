export default function EditorialPolicy({ params }) {
  const lang = params?.lang || 'bn'
  const c = content[lang] || content.bn
  const isBangla = lang === 'bn'
  const fontClass = isBangla ? 'font-bangla' : 'font-latin'

  return (
    <div className={`container mx-auto px-4 py-8 max-w-3xl ${fontClass}`}>
      <h1 className="text-3xl font-bold mb-2">{c.title}</h1>

      <p className="text-sm text-gray-500 mb-6">{c.lastUpdated}</p>

      <p className="mb-8 text-gray-700 leading-relaxed">{c.intro}</p>

      <div className="space-y-6">
        {c.sections.map((section, i) => (
          <section key={i}>
            <h2 className="text-xl font-semibold mb-2">{section.heading}</h2>

            <p className="text-gray-700 leading-relaxed">{section.body}</p>

            {section.link && (
              <a
                href={section.link.href.startsWith('http')
                  ? section.link.href
                  : `/${lang}${section.link.href}`}
                target={section.link.href.startsWith('http') ? '_blank' : undefined}
                rel={section.link.href.startsWith('http') ? 'noopener noreferrer' : undefined}
                className="inline-block mt-2 text-red-600 hover:text-red-700 hover:underline"
              >
                {section.link.text} →
              </a>
            )}
          </section>
        ))}
      </div>

      {c.outro && (
        <p className="mt-8 pt-6 border-t border-gray-200 text-gray-700 leading-relaxed">
          {c.outro}
        </p>
      )}
    </div>
  )
}
